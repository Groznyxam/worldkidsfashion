// Builds a reverse map: English text → translation key
// Then walks the DOM and translates matching text nodes

function wkfBuildReverseMap(langCode) {
  const en = WKF_LANGS['en'];
  const t  = WKF_LANGS[langCode];
  const map = {};
  for (const key in en) {
    if (key === 'flag' || key === 'name') continue;
    const enVal = en[key];
    const trVal = t[key];
    if (enVal && trVal && enVal !== trVal) {
      // Strip HTML tags for matching
      const plain = enVal.replace(/<[^>]+>/g, '').trim();
      if (plain.length > 2) map[plain] = { key, html: trVal };
    }
  }
  return map;
}


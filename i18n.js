const LANG_MAP = { ru:'ru', fr:'fr', tr:'tr', de:'de', no:'no', nb:'no', nn:'no' };

function wkfDetectLang() {
  const saved = localStorage.getItem('wkf_lang');
  if (saved && WKF_LANGS[saved]) return saved;
  const browser = (navigator.language || 'en').toLowerCase().split('-')[0];
  return LANG_MAP[browser] || 'en';
}

function wkfSetLang(code) {
  if (!WKF_LANGS[code]) return;
  localStorage.setItem('wkf_lang', code);
  const t = WKF_LANGS[code];
  document.documentElement.lang = code;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) el.innerHTML = t[key];
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    if (t[key] !== undefined) el.placeholder = t[key];
  });
  const btn = document.getElementById('langBtn');
  const lc = document.getElementById("langCode"); if(lc) lc.textContent = code.toUpperCase();
  const dd = document.getElementById('langDropdown');
  if (dd) dd.style.display = 'none';
  document.querySelectorAll('.lang-opt').forEach(o => {
    o.style.background = o.getAttribute('data-lang') === code ? 'rgba(201,168,76,.15)' : '';
    o.style.color = o.getAttribute('data-lang') === code ? 'var(--gold)' : '';
  });
}

function wkfToggleLang() {
  const dd = document.getElementById('langDropdown');
  if (!dd) return;
  dd.style.display = dd.style.display === 'block' ? 'none' : 'block';
}

function wkfInitLang() {
  wkfSetLang(wkfDetectLang());
}

document.addEventListener('click', function(e) {
  const wrap = document.getElementById('langWrap');
  const dd   = document.getElementById('langDropdown');
  if (wrap && dd && !wrap.contains(e.target)) dd.style.display = 'none';
});

